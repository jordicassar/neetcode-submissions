your_dict = { 
  "a": 10, 
  "apple": 12,
  "bat": 7
}

# Print the dictionary itself.
print(your_dict)
# Print the value of the key "a".
print(your_dict["a"])
# Print True or False depending on whether the key "d" is in the dictionary.
print("d" in your_dict)
# Reassign the value of the key "a" to 4.
your_dict["a"] = 4
# Print dict again
print(your_dict)